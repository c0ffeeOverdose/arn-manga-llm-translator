#!/usr/bin/env node
// Regenerates src/content/thai-words.ts: repairs for ICU's Thai word break.
// - THAI_SPLIT_WORDS: words ICU keeps whole standalone but cuts inside in context
//   (จริง|เห|รอ); render.ts merges ICU units across boundaries inside them.
//   A word ICU splits the SAME way standalone is a real compound (สุด|ยอด) and stays.
// - THAI_TAIL_TRIGGERS/THAI_TAIL_UNSAFE: colloquial tail particles ICU mis-resyncs on
//   (…ประโยชน์เนี่ยนะ → ประ|โย|ชน์เนี่ย). render.ts splits the run BEFORE the tail so
//   ICU never sees the junction; unsafe words (ขันหมาก, ปัสสาวะ) end with a trigger and
//   must not be split inside.
// Source: PyThaiNLP words_th.txt (CC0-1.0), pinned tag — network needed to regenerate.
// The oracle is the Node ICU build, so regenerate with the Node version used in CI.
import { createHash } from 'crypto';
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';

const TAG = 'v5.3.8';
const SOURCE = `https://raw.githubusercontent.com/PyThaiNLP/pythainlp/${TAG}/pythainlp/corpus/words_th.txt`;
const OUT = fileURLToPath(new URL('../src/content/thai-words.ts', import.meta.url));
const MAX_LEN = 6; // thaiWords() in render.ts must scan up to this length
// Prefix/suffix probe contexts: each pair forces ICU to segment a word boundary
// right before W, the condition under which it mis-segments the words above.
const PRE = ['ดี', 'ไป', 'จริง', 'นะ', 'ฉัน'];
const POST = ['ดี', 'นะ', 'ไป', 'ครับ'];
// Tail particles worth testing: colloquial particles ICU's dictionary does not cover.
const TAIL_CANDIDATES = [
    'เนี่ยนะ', 'เนี่ย', 'น่ะ', 'อ่ะ', 'ป่ะ', 'ม่ะ', 'ดิ', 'รึเปล่า', 'หรอ', 'เหอะ',
    'จ้า', 'จ๊ะ', 'จ้ะ', 'เด้อ', 'น้อ', 'หว่า', 'วะ', 'โว้ย', 'ล่ะ', 'อ่ะนะ',
    'สิ', 'นะ', 'จัง', 'เลย', 'ไหม', 'มั้ย', 'เหรอ', 'หรือ', 'อยู่', 'ด้วย',
    'มาก', 'แล้ว', 'กัน', 'ครับ', 'ค่ะ', 'คะ',
];

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`fetch ${SOURCE} -> ${res.status}`);
const source = await res.text();
const sha256 = createHash('sha256').update(source).digest('hex');

const segmenter = new Intl.Segmenter('th', { granularity: 'word' });
const parts = (t) => [...segmenter.segment(t)].map(s => s.segment).filter(w => w.trim());
const ownBounds = (w) => {
    const out = new Set();
    let p = 0;
    for (const u of parts(w)) { p += u.length; if (p < w.length) out.add(p); }
    return out;
};

// Probe cuts inside w at a position w's standalone segmentation doesn't have.
function misaligned(probe, w) {
    const start = probe.indexOf(w);
    if (start < 0) return false;
    const own = ownBounds(w);
    let p = 0;
    for (const u of parts(probe)) {
        p += u.length;
        if (p > start && p < start + w.length && !own.has(p - start)) return true;
    }
    return false;
}

const lexicon = [...new Set(source.split(/\r?\n/).map(s => s.trim()).filter(Boolean))]
    .filter(w => /^[\p{Script=Thai}]+$/u.test(w) && [...w].length >= 2);

const words = lexicon
    .filter(w => [...w].length <= MAX_LEN)
    .filter(w => PRE.some(p => misaligned(p + w, w)) || POST.some(q => misaligned(w + q, w)));

// A tail is a trigger when it mis-splits at least one word ICU keeps whole standalone.
const triggers = TAIL_CANDIDATES
    .filter(t => lexicon.some(w => [...w].length <= 8 && parts(w).length === 1 && misaligned(w + t, w)))
    .sort((a, b) => b.length - a.length);
// Words that END with a trigger: splitting before the trigger would cut inside them.
const unsafe = lexicon.filter(w => triggers.some(t => w.length > t.length && w.endsWith(t)));

writeFileSync(OUT, `// Generated by scripts/make-thai-words.mjs — do not edit.
// Source: PyThaiNLP words_th.txt @ ${TAG} (CC0-1.0), sha256 ${sha256}
// THAI_SPLIT_WORDS: words ICU leaves whole standalone but cuts in context; thaiWords()
// merges ICU units across boundaries inside them.
// THAI_TAIL_TRIGGERS / THAI_TAIL_UNSAFE: tail particles ICU mis-resyncs on, and real
// words ending with one that must never be split before it.
export const THAI_SPLIT_WORDS = \`${words.join('\n')}\`;
export const THAI_TAIL_TRIGGERS = \`${triggers.join('\n')}\`;
export const THAI_TAIL_UNSAFE = \`${unsafe.join('\n')}\`;
`);
console.log(`${words.length} split words, ${triggers.length} tail triggers, ${unsafe.length} unsafe words -> ${OUT}`);
console.log(`source ${TAG} sha256 ${sha256}`);
